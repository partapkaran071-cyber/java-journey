package basic_chijein.Basicprogrammes;

public class problem03TSAofaCuboid {
    public static void main(String[] args) {
        double length = 10;
        double breadth = 30;
        double height = 20.6;
        double TSA = 2*(length*breadth+breadth*height+length*height);
        System.out.println("Total surface area of cuboid :-"+TSA);
        //+ is used to print declared double or int


    }
}
