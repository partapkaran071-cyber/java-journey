package Methods;

public class Builtin {
    public static void main(String[] args) {
       System.out.println(Math.sqrt(100));//square root
        System.out.println(Math.cbrt(100));//cube root
       System.out.println(Math.abs(-45));//absolute value
        System.out.println(Math.floor(9.8));//greatest integer
        System.out.println(Math.ceil(3.0001));//ceiling
        System.out.println(Math.min(10,15));//minimum number
        System.out.println(Math.max(100,101));//maximum number

    }
}
